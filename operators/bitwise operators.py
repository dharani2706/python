#B5.1 - bitwise operators
p = 12
q = 29
print("Binary of p:", bin(p))
print("Binary of q:", bin(q))
print("AND:", p & q)
print("OR:", p | q)
print("XOR:", p ^ q)
print("NOT:", ~p)
print("Left Shift:", p << 2)
print("Right Shift:", p >> 2)
# Binary of p: 0b1100
# Binary of q: 0b11101
# AND: 12
# OR: 29
# XOR: 17
# NOT: -13
# Left Shift: 48
# Right Shift: 3