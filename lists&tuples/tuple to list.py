my_list = [10, 20, 30, 40]
my_tuple = tuple(my_list)
print("List:", my_list)
print("Tuple:", my_tuple)
new_tuple = (50, 60, 70, 80)
new_list = list(new_tuple)
print("Tuple:", new_tuple)
print("List:", new_list)
#output:
List: [10, 20, 30, 40]
Tuple: (10, 20, 30, 40)
Tuple: (50, 60, 70, 80)
List: [50, 60, 70, 80]
